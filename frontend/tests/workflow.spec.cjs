test('advanced manifest upload and validation remain available on demand',async({page,request})=>{
 const manifest=JSON.parse(fs.readFileSync(fixture('corrected-broker.manifest.json'),'utf8'))
 const deliveries=await (await request.get('/api/scopes/demo-scope/deliveries')).json()
 manifest.revision=deliveries.deliveries.find(d=>d.side==='BROKER').batches[0].revision+1
 await page.goto('/?scope=demo-scope')
 await expect(page.getByText('Connected',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'More options'}).click()
 await page.getByText('Existing inputs & manifests',{exact:true}).click()
 await page.getByRole('button',{name:'Upload broker with manifest',exact:true}).click()
 await page.getByLabel('CSV file',{exact:true}).setInputFiles(fixture('corrected-broker.csv'))
 await page.getByLabel('Producer manifest',{exact:true}).fill(JSON.stringify(manifest))
 await page.getByRole('button',{name:'Upload & validate',exact:true}).click()
 await expect(page.getByText('Delivery registered. Validation will run in the background.',{exact:true})).toBeVisible()
 let latest
 await expect.poll(async()=>{const x=await (await request.get('/api/scopes/demo-scope/deliveries')).json();latest=x.deliveries.find(d=>d.side==='BROKER').batches[0];return latest.status}).toBe('READY')
 expect(latest.revision).toBe(manifest.revision)
 expect(latest.sha256).toBe(manifest.sha256)
 await page.getByRole('button',{name:'More options'}).click()
 await page.getByText('Existing inputs & manifests',{exact:true}).click()
 await expect(page.getByLabel('BROKER revision')).toHaveValue(latest.id)
 await page.locator('.existing-input').nth(1).getByRole('button',{name:'View validation'}).click()
 await expect(page.getByRole('dialog',{name:`Broker delivery · revision ${manifest.revision}`})).toContainText('Producer manifest')
})

test('invalid manual CSV shows validation evidence without changing published results',async({page,request})=>{
 const before=await (await request.get('/api/scopes')).json()
 const published=before.find(s=>s.id==='demo-scope').published_run_id
 await choosePair(page,'small/internal.csv','rejected-broker.csv')
 const w=await submitPair(page)
 await expect(page.getByRole('status',{name:'Manual workflow status'})).toContainText('File validation needs attention')
 await page.getByRole('button',{name:'Broker validation',exact:true}).click()
 const validation=page.getByRole('dialog',{name:/Broker delivery/})
 await expect(validation.locator('.rejection')).toContainText('INVALID_DECIMAL')
 await expect(validation.locator('.rejection')).toContainText('NaN')
 const current=await (await request.get('/api/scopes')).json()
 expect(current.find(s=>s.id==='demo-scope').published_run_id).toBe(published)
 const workflow=await (await request.get('/api/workflows/'+w.id)).json()
 expect(workflow.run_id).toBeNull()
 // Leave a completed, inspectable demo in the visible workspace after the error check.
 await choosePair(page,'small/internal.csv','small/broker.csv')
 await finish(request,await submitPair(page))
 await expect(page.locator('.result-run .badge.succeeded')).toBeVisible()
 await expect(page.locator('.result-stat.matched strong')).toHaveText('45')
 await page.goto('/?scope=demo-scope')
 await expect(page.getByText('Connected',{exact:true})).toBeVisible()
 await expect(page.locator('.case-table tbody tr').first()).toBeVisible()
 await page.screenshot({path:'test-results/sidebar-workspace-desktop.png',fullPage:true})
})
